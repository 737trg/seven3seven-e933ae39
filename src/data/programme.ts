import type { Programme, Session, SessionBlock, Week } from "@/types/programme";

/* Helper to build blocks compactly. */
const b = (
  order: number,
  kind: SessionBlock["kind"],
  title: string,
  timeWindow: string | undefined,
  lines: string[],
  extras: Partial<SessionBlock> = {},
): SessionBlock => ({
  id: `b${order}`,
  order,
  kind,
  title,
  timeWindow,
  lines,
  ...extras,
});

const session = (
  weekNumber: number,
  day: Session["day"],
  date: string,
  title: string,
  category: Session["category"],
  duration: string,
  purpose: string,
  expectedEffort: string,
  blocks: SessionBlock[],
  coachNote?: string,
  completed = false,
): Session => ({
  id: `w${weekNumber}-${day.slice(0, 3).toLowerCase()}`,
  weekNumber,
  day,
  date,
  title,
  category,
  duration,
  purpose,
  expectedEffort,
  blocks,
  coachNote,
  completed,
});

